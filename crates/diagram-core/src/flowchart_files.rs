use serde::Serialize;
use std::fs;
use std::io::{self, Write};
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

const LIBRARY: &str = "bsuir-core/src/block-schemes/lib.typ";
const GENERATED: &str = "// Generated by Diagramator from a block scheme.";
const RENDERER: &str = include_str!("../../../examples/flowcharts/flowchart.typ");

#[derive(Clone, Debug, PartialEq, Eq, Serialize, serde::Deserialize)]
pub struct Revision {
    pub json: Option<String>,
    pub typst: Option<String>,
}

#[derive(Serialize)]
pub struct SavedFlowchart {
    pub revision: Revision,
    pub export_error: Option<String>,
}

fn read_optional(path: &Path) -> io::Result<Option<String>> {
    match fs::read_to_string(path) {
        Ok(contents) => Ok(Some(contents)),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(error),
    }
}

pub fn read_pair(path: &Path) -> io::Result<Revision> {
    Ok(Revision {
        json: read_optional(path)?,
        typst: read_optional(&path.with_extension("typ"))?,
    })
}

fn stage(dir: &Path, contents: &str) -> io::Result<tempfile::NamedTempFile> {
    let mut file = tempfile::Builder::new().suffix(".typ").tempfile_in(dir)?;
    file.write_all(contents.as_bytes())?;
    file.as_file().sync_all()?;
    Ok(file)
}

fn typst_source(path: &Path, data: &str) -> Result<(String, PathBuf, String), String> {
    let dir = path
        .parent()
        .ok_or("Choose a folder for the block scheme.")?;
    let (levels, root) = dir
        .ancestors()
        .enumerate()
        .find(|(_, ancestor)| ancestor.join(LIBRARY).is_file())
        .ok_or("Could not find bsuir-core in the save folder or its parent folders.")?;
    let import = format!("{}{}", "../".repeat(levels), LIBRARY);
    let stem = path
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or_default();
    let function = if stem.as_bytes().first().is_some_and(u8::is_ascii_alphabetic)
        && stem
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || c == b'-' || c == b'_')
        && stem != "draw-flowchart"
        && stem != "bsuir-blocks"
    {
        stem.to_owned()
    } else {
        "flowchart".to_owned()
    };
    let quoted = serde_json::to_string(data).map_err(|e| e.to_string())?;
    let source = format!("{GENERATED}\n#import \"{import}\" as bsuir-blocks\n{RENDERER}\n#let {function}() = draw-flowchart(json(bytes({quoted})), bsuir-blocks)\n");
    Ok((source, root.to_owned(), function))
}

fn prepare_typst(
    typst: &Path,
    path: &Path,
    data: &str,
) -> Result<(String, tempfile::NamedTempFile), String> {
    let (source, root, function) = typst_source(path, data)?;
    let dir = path
        .parent()
        .ok_or("Choose a folder for the block scheme.")?;
    let preview = stage(dir, &format!("{source}\n#{function}()\n")).map_err(|e| e.to_string())?;
    let output = Command::new(typst)
        .args(["compile", "--format", "pdf", "--root"])
        .arg(root)
        .arg(preview.path())
        .arg("-")
        .stdout(Stdio::null())
        .output()
        .map_err(|e| e.to_string())?;
    if !output.status.success() {
        return Err(String::from_utf8_lossy(&output.stderr).trim().to_owned());
    }
    let file = stage(dir, &source).map_err(|e| e.to_string())?;
    Ok((source, file))
}

pub fn save_pair(
    typst: &Path,
    path: &Path,
    json: String,
    render_data: &str,
    expected: Revision,
) -> Result<SavedFlowchart, String> {
    if path.extension().and_then(|ext| ext.to_str()) != Some("json") {
        return Err("Choose a .json filename for the block scheme.".into());
    }
    let path = std::path::absolute(path).map_err(|e| e.to_string())?;
    let typ_path = path.with_extension("typ");
    let check = || -> Result<(), String> {
        if read_pair(&path).map_err(|e| e.to_string())? != expected {
            return Err("The JSON or Typst file changed on disk. Use Save As to keep your edits in a new pair.".into());
        }
        if expected
            .typst
            .as_ref()
            .is_some_and(|text| !text.starts_with(GENERATED))
        {
            return Err(
                "The companion Typst file is hand-written. Use Save As to choose a new pair."
                    .into(),
            );
        }
        Ok(())
    };
    check()?;
    let exported = prepare_typst(typst, &path, render_data);
    let draft =
        stage(path.parent().ok_or("Choose a save folder.")?, &json).map_err(|e| e.to_string())?;
    check()?;
    draft.persist(&path).map_err(|e| e.to_string())?;
    let mut revision = Revision {
        json: Some(json),
        typst: expected.typst,
    };
    let export_error = match exported {
        Ok((source, file)) => match file.persist(&typ_path) {
            Ok(_) => {
                revision.typst = Some(source);
                None
            }
            Err(error) => Some(error.to_string()),
        },
        Err(error) => Some(error),
    };
    Ok(SavedFlowchart {
        revision,
        export_error,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn invalid_export_keeps_the_previous_typst_and_a_conflict_keeps_both_files() {
        let folder = tempfile::tempdir().unwrap();
        let path = folder.path().join("order-flow.json");
        let typ = path.with_extension("typ");
        fs::write(&path, "old draft").unwrap();
        fs::write(&typ, GENERATED).unwrap();
        let expected = read_pair(&path).unwrap();

        // This directory has no library. The draft is still saved and the last
        // generated output remains available to the enclosing report.
        let result = save_pair(
            Path::new("typst"),
            &path,
            "new draft".into(),
            "{}",
            expected,
        )
        .unwrap();
        assert!(result.export_error.is_some());
        assert_eq!(fs::read_to_string(&path).unwrap(), "new draft");
        assert_eq!(fs::read_to_string(&typ).unwrap(), GENERATED);

        fs::write(&typ, "external edit").unwrap();
        assert!(save_pair(
            Path::new("typst"),
            &path,
            "stale draft".into(),
            "{}",
            result.revision
        )
        .is_err());
        assert_eq!(fs::read_to_string(&path).unwrap(), "new draft");
        assert_eq!(fs::read_to_string(&typ).unwrap(), "external edit");
    }
}
